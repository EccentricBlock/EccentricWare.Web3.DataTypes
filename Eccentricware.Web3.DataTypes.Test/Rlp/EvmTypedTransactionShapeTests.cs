            var envelope = FromHex(signed.SignedHex);
            var expected = FromHex(signed.TransactionHashHex);
            var wrapped = EncodeString(envelope);
            var outer = DecodeOk(wrapped);

            CollectionAssert.AreEqual(expected, Keccak(outer.Payload), $"{name}: Keccak of the wrapped string's payload (type || rlp(payload), as received)");
            CollectionAssert.AreEqual(expected, Keccak(envelope), $"{name}: Keccak of the envelope bytes");
            Assert.AreEqual(type, outer.Payload[0], name);

            CollectionAssert.AreNotEqual(expected, Keccak(outer.Payload[1..]), $"{name}: without the type byte");
            CollectionAssert.AreNotEqual(expected, Keccak(outer.Encoded), $"{name}: over the RLP string header too");

            // Re-encoding the decoded list reproduces the received bytes (strict decoding is canonical), so hashing a re-encoding is also the same hash.
            var inner = DecodeOk(outer.Payload[1..].ToArray());
            var rebuilt = new byte[1 + inner.EncodedLength];
            rebuilt[0] = type;
            Assert.AreEqual(RLPStatus.Success, inner.TryCopyEncodedTo(rebuilt.AsSpan(1), out _), name);
            CollectionAssert.AreEqual(expected, Keccak(rebuilt), $"{name}: hash of type || the item's own encoded bytes");
        }
    }

    [TestMethod]
    public void SigningPreimage_IsTheTypeByteThenTheListWithoutTheThreeSignatureFields_AndItsKeccakIsTheSigningHash()
    {
        foreach (var (name, type, signed) in AllSignedVectors())
        {
            var root = DecodePayload(FromHex(signed.SignedHex), type, name);
            Assert.AreEqual(RLPStatus.Success, root.TryIndexDirectChildren(new RLPRange[20], out var index, out _), name);
            var signedFieldCount = index.Count - 3;

            var unsignedPayload = 0;
            for (var i = 0; i < signedFieldCount; i++)
            {
                unsignedPayload += Child(index, i).EncodedLength;
            }

            var preimage = new byte[1 + ListLength(unsignedPayload)];
            preimage[0] = type;
            RLPData field = default; // declared before the writer: TryWriteEncoded's ref-safety rules need the item to outlive it
            var writer = new RLPWriter(preimage.AsSpan(1), new int[4]);
            Assert.AreEqual(RLPStatus.Success, writer.TryBeginList(unsignedPayload), name);
            for (var i = 0; i < signedFieldCount; i++)
            {
                field = Child(index, i);
                Assert.AreEqual(RLPStatus.Success, writer.TryWriteEncoded(in field), $"{name}: field {i}");
            }

            Assert.AreEqual(RLPStatus.Success, writer.TryEndList(), name);
            Assert.AreEqual(RLPStatus.Success, writer.TryComplete(out var written), name);
            Assert.AreEqual(preimage.Length - 1, written, name);

            CollectionAssert.AreEqual(FromHex(signed.PreimageHex), preimage, $"{name}: preimage equals Nethereum's GetRLPEncodedRaw");
            CollectionAssert.AreEqual(FromHex(signed.SigningHashHex), Keccak(preimage), $"{name}: Keccak(type || rlp(unsigned fields)) is the signing hash");
            CollectionAssert.AreNotEqual(FromHex(signed.SigningHashHex), FromHex(signed.TransactionHashHex), $"{name}: signing hash and transaction hash differ");
        }
    }

