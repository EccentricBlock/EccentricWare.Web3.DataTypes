    private static byte[] FromHex(string hex) => Convert.FromHexString(hex);

    private static byte[] Pad32Hex(string hex)
    {
        var raw = Convert.FromHexString(hex);
        var padded = new byte[32];
        raw.CopyTo(padded, 32 - raw.Length);
        return padded;
    }

    private static uint256 U256(string decimalText) => new(Padded32(BigInteger.Parse(decimalText, CultureInfo.InvariantCulture)));

    private static byte[] Keccak(ReadOnlySpan<byte> bytes)
    {
        var digest = new byte[32];
        Keccak256.ComputeHash(bytes, digest);
        return digest;
    }

    private static byte[] Sha256(ReadOnlySpan<byte> bytes) => SHA256.HashData(bytes);

    /// <summary>Synthetic blob content: byte i of blob k is <c>i * 131 + k * 17 + 7</c> (mod 256). The generator used the same formula.</summary>
    private static byte[] Blob(int blobIndex)
    {
        var blob = new byte[BlobByteLength];
        for (var i = 0; i < blob.Length; i++)
        {
            blob[i] = (byte)((i * 131) + (blobIndex * 17) + 7);
        }

        return blob;
    }

    /// <summary>Every signed vector with its name and EIP-2718 type byte.</summary>
    private static IEnumerable<(string Name, byte Type, SignedTypedVector Signed)> AllSignedVectors()
    {
        foreach (var vector in Eip2930Vectors)
        {
            yield return (vector.Name, 0x01, vector.Signed);
        }

        foreach (var vector in Eip4844Vectors)
        {
            yield return (vector.Name, 0x03, vector.Signed);
        }

        yield return (Eip7702.Name, 0x04, Eip7702.Signed);
    }

    /// <summary>Decodes the bytes after the type byte; the envelope's first byte must be <paramref name="type"/>.</summary>
    private static RLPData DecodePayload(byte[] envelope, byte type, string name, RLPDecodeLimits? limits = null)
    {
        Assert.AreEqual(type, envelope[0], $"{name}: type byte");
        return DecodeOk(envelope[1..], limits);
    }

    private static RLPChildrenIndex IndexOf(scoped in RLPData list, RLPRange[] workspace, int expectedCount, string name)
    {
        Assert.AreEqual(RLPKind.List, list.Kind, name);
        Assert.AreEqual(RLPStatus.Success, list.TryIndexDirectChildren(workspace, out var index, out _), name);
        Assert.AreEqual(expectedCount, index.Count, $"{name}: field count");
        return index;
    }

    private static RLPData Child(scoped in RLPChildrenIndex index, int ordinal)
    {
        Assert.AreEqual(RLPStatus.Success, index.TryGetAt(ordinal, out var child), $"field {ordinal}");
        return child;
    }

    private static void AssertUInt64(in RLPData item, ulong expected, string what)
    {
        Assert.AreEqual(RLPStatus.Success, item.TryGetUInt64(out var value), what);
        Assert.AreEqual(expected, value, what);
        Assert.AreEqual(RLPStatus.Success, item.TryGetUInt256(out var wide), what);
        Assert.AreEqual(new uint256(expected), wide, $"{what} as uint256");
    }

    private static void AssertUInt256(in RLPData item, string decimalText, string what)
    {
        Assert.AreEqual(RLPStatus.Success, item.TryGetUInt256(out var value), what);
        Assert.AreEqual(U256(decimalText), value, what);
    }

