    [TestMethod]
    public void PostMergeHeaderNonce_IsAValidEightByteString_ButNotACanonicalInteger()
    {
        var nonce = H("88 0000000000000000");
        var item = DecodeOk(nonce);
        Assert.AreEqual(RLPKind.ByteString, item.Kind);
        Assert.AreEqual(8, item.PayloadLength);

        // As integers: a leading zero byte is non-canonical; the accessors say so and leave the value zero.
        Assert.AreEqual(RLPStatus.NonCanonicalInteger, item.TryGetUInt64(out var narrow));
        Assert.AreEqual(0UL, narrow);
        Assert.AreEqual(RLPStatus.NonCanonicalInteger, item.TryGetUInt256(out var wide));
        Assert.AreEqual(uint256.Zero, wide);
        Assert.AreEqual(RLPStatus.InvalidFixedLength, item.TryGetHash32(out _));

        // As bytes it reads fine, which is how a header nonce must be handled.
        Assert.IsTrue(item.Payload.SequenceEqual(new byte[8]));
        var copy = new byte[9];
        Assert.AreEqual(RLPStatus.Success, item.TryCopyEncodedTo(copy, out var written));
        Assert.AreEqual(9, written);
        CollectionAssert.AreEqual(nonce, copy);

        // A pre-merge style nonce with a non-zero first byte is an ordinary 8-byte integer.
        var legacyNonce = DecodeOk(H("88 0102030405060708"));
        Assert.AreEqual(RLPStatus.Success, legacyNonce.TryGetUInt64(out var value));
        Assert.AreEqual(0x0102030405060708UL, value);
    }

    [TestMethod]
    public void LogsBloom_IsAValid256ByteString_ButNotAHash32AndNotAnInteger()
    {
        foreach (var firstByte in new byte[] { 0x00, 0x80 })
        {
            var bloomBytes = Pattern(256, firstByte);
            var encoded = new byte[259];
            encoded[0] = 0xb9;
            encoded[1] = 0x01;
            encoded[2] = 0x00;
            bloomBytes.CopyTo(encoded, 3);
            CollectionAssert.AreEqual(EncodeString(bloomBytes), encoded, "hand-written b9 01 00 header equals the oracle's");

            var item = DecodeOk(encoded);
            Assert.AreEqual(RLPKind.ByteString, item.Kind);
            Assert.AreEqual(256, item.PayloadLength);
            Assert.AreEqual(259, item.EncodedLength);
            Assert.AreEqual(RLPStatus.InvalidFixedLength, item.TryGetHash32(out var hash), $"first byte {firstByte:x2}");
            Assert.AreEqual(default(Hash32), hash);
            Assert.AreEqual(RLPStatus.InvalidFixedLength, item.TryGetAddress(out _));
            Assert.AreEqual(firstByte == 0 ? RLPStatus.NonCanonicalInteger : RLPStatus.IntegerOverflow, item.TryGetUInt256(out _), $"first byte {firstByte:x2}");
            Assert.AreEqual(firstByte == 0 ? RLPStatus.NonCanonicalInteger : RLPStatus.IntegerOverflow, item.TryGetUInt64(out _), $"first byte {firstByte:x2}");
            Assert.IsTrue(item.Payload.SequenceEqual(bloomBytes), "read as bytes it is intact");
        }
    }

    [TestMethod]
    public void HeaderShapedList_WithABloomAndANonce_EnumeratesThemAsByteStrings()
    {
        // SELF-BUILT: [ bloom (256 bytes), mixHash (32 bytes), nonce (8 zero bytes) ], the field shapes of a post-merge header tail.
        var list = DecodeOk(RlpReference.Encode(RlpNode.ListOf(RlpNode.Bytes(Pattern(256, 0x00)), RlpNode.Bytes(Pattern(32, 0x33)), RlpNode.Bytes(new byte[8]))));
        var index = IndexOf(list, new RLPRange[4], 3, "header tail");
        Assert.AreEqual(RLPStatus.InvalidFixedLength, Child(index, 0).TryGetHash32(out _), "bloom");
        Assert.AreEqual(RLPStatus.Success, Child(index, 1).TryGetHash32(out _), "mix hash is a Hash32");
        Assert.AreEqual(RLPStatus.NonCanonicalInteger, Child(index, 2).TryGetUInt64(out _), "nonce");
        Assert.AreEqual(8, Child(index, 2).PayloadLength);
    }
