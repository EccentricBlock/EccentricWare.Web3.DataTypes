    // ------------------------------------------------------------------ EIP-4844 network form: [payload_body, blobs, commitments, proofs]

    /// <summary>Builds <c>03 || rlp([payload_body, blobs, commitments, proofs])</c> with this library's writer.</summary>
    private static byte[] BuildNetworkForm(byte[] payloadBodyEnvelope, IReadOnlyList<byte[]> blobs, string[] commitments, string[] proofs)
    {
        var body = DecodeOk(payloadBodyEnvelope[1..]);
        var blobsLength = ListPayloadOfStrings(blobs.Select(b => b.Length));
        var commitmentsLength = ListPayloadOfStrings(commitments.Select(c => c.Length / 2));
        var proofsLength = ListPayloadOfStrings(proofs.Select(p => p.Length / 2));
        var total = body.EncodedLength + ListLength(blobsLength) + ListLength(commitmentsLength) + ListLength(proofsLength);
        var destination = new byte[1 + ListLength(total)];
        destination[0] = 0x03;
        var writer = new RLPWriter(destination.AsSpan(1), new int[4]);
        Assert.AreEqual(RLPStatus.Success, writer.TryBeginList(total));
        Assert.AreEqual(RLPStatus.Success, writer.TryWriteEncoded(in body));
        Assert.AreEqual(RLPStatus.Success, writer.TryBeginList(blobsLength));
        foreach (var blob in blobs)
        {
            Assert.AreEqual(RLPStatus.Success, writer.TryWriteByteString(blob));
        }

        Assert.AreEqual(RLPStatus.Success, writer.TryEndList());
        Assert.AreEqual(RLPStatus.Success, writer.TryBeginList(commitmentsLength));
        foreach (var commitment in commitments)
        {
            Assert.AreEqual(RLPStatus.Success, writer.TryWriteByteString(FromHex(commitment)));
        }

        Assert.AreEqual(RLPStatus.Success, writer.TryEndList());
        Assert.AreEqual(RLPStatus.Success, writer.TryBeginList(proofsLength));
        foreach (var proof in proofs)
        {
            Assert.AreEqual(RLPStatus.Success, writer.TryWriteByteString(FromHex(proof)));
        }

        Assert.AreEqual(RLPStatus.Success, writer.TryEndList());
        Assert.AreEqual(RLPStatus.Success, writer.TryEndList());
        Assert.AreEqual(RLPStatus.Success, writer.TryComplete(out var written));
        Assert.AreEqual(destination.Length - 1, written);
        return destination;
    }

    private static int ListPayloadOfStrings(IEnumerable<int> payloadLengths)
    {
        var sum = 0;
        foreach (var length in payloadLengths)
        {
            Assert.AreEqual(RLPStatus.Success, RLPEncoder.TryGetByteStringLength(FakeLengthSpan(length), out var total));
            sum += total;
        }

        return sum;
    }

    private static int ListLength(int payloadLength)
    {
        Assert.AreEqual(RLPStatus.Success, RLPEncoder.TryGetListLength(payloadLength, out var total));
        return total;
    }

